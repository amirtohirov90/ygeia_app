import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';

class LessonDetailScreen extends StatelessWidget {
  final String category;
  final Color color;
  final IconData icon;

  const LessonDetailScreen({
    super.key,
    required this.category,
    required this.color,
    required this.icon,
  });

  @override
  Widget build(BuildContext context) {
    final lessons = _lessonData[category] ?? [];

    return Scaffold(
      backgroundColor: const Color(0xFFF8F6F2),
      appBar: AppBar(
        backgroundColor: color,
        iconTheme: const IconThemeData(color: Colors.white),
        title: Text(
          category,
          style: GoogleFonts.playfairDisplay(
            color: Colors.white,
            fontSize: 22,
            fontWeight: FontWeight.bold,
          ),
        ),
      ),
      body: ListView.builder(
        padding: const EdgeInsets.all(16),
        itemCount: lessons.length,
        itemBuilder: (context, index) {
          final lesson = lessons[index];
          return _LessonCard(
            number: index + 1,
            title: lesson['title']!,
            duration: lesson['duration']!,
            color: color,
            onTap: () => _showLesson(context, lesson, color),
          );
        },
      ),
    );
  }

  void _showLesson(
      BuildContext context, Map<String, String> lesson, Color color) {
    Navigator.push(
      context,
      MaterialPageRoute(
        builder: (_) => _LessonContentScreen(lesson: lesson, color: color),
      ),
    );
  }
}

class _LessonCard extends StatelessWidget {
  final int number;
  final String title;
  final String duration;
  final Color color;
  final VoidCallback onTap;

  const _LessonCard({
    required this.number,
    required this.title,
    required this.duration,
    required this.color,
    required this.onTap,
  });

  @override
  Widget build(BuildContext context) {
    return Container(
      margin: const EdgeInsets.only(bottom: 12),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(14),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withOpacity(0.04),
            blurRadius: 8,
            offset: const Offset(0, 3),
          ),
        ],
      ),
      child: ListTile(
        contentPadding:
            const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
        leading: Container(
          width: 44,
          height: 44,
          decoration: BoxDecoration(
            color: color.withOpacity(0.12),
            borderRadius: BorderRadius.circular(10),
          ),
          child: Center(
            child: Text(
              '$number',
              style: GoogleFonts.playfairDisplay(
                fontSize: 18,
                fontWeight: FontWeight.bold,
                color: color,
              ),
            ),
          ),
        ),
        title: Text(
          title,
          style: GoogleFonts.inter(
            fontSize: 15,
            fontWeight: FontWeight.w600,
            color: const Color(0xFF1A1A1A),
          ),
        ),
        subtitle: Text(
          duration,
          style: GoogleFonts.inter(
            fontSize: 12,
            color: const Color(0xFF999999),
          ),
        ),
        trailing: Icon(Icons.play_circle_outline, color: color, size: 28),
        onTap: onTap,
      ),
    );
  }
}

